/**
 * The digests of every first-set (v1) revision of each wizard seed text (specs/20261115-crm-offer-wizard T61;
 * DD-59, DD-60, AC-12.5).
 *
 *   bun scripts/seed-digests.ts            # prints the record
 *   bun scripts/seed-digests.ts --write    # rewrites src/offer-templates/wizardSeeds/v1Digests.ts (refused when a seed has no v1 revision in the history)
 *   bun scripts/seed-digests.ts --check    # exits 1 when the history holds v1 revisions that disagree with the file;
 *                                          # a seed with no v1 revision in the history is skipped (the file is authoritative since the squash)
 *
 * A v1 text is what a seed file exported before the issuer moved to the entity profile: any revision in the file's
 * git history that does not yet declare `EMITTENTE`. A database that was seeded on this branch may hold any of them
 * (T2 and T4 were revised after their first conversion), so the one-time upgrade (T63) recognises a stored row by the
 * SHA-256 of its text matching one of these and by nothing else (exact match only: an edited text never matches).
 * The digest is of the text exactly as the seed exports it (the template literal's value), as the upgrade will read
 * it from the row.
 *
 * Needs the git history of the seed files; reads nothing else and writes only the data file, with `--write`.
 */

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";

export type SeedCode = "T1" | "T2" | "T3" | "T4" | "T5" | "T6" | "T1+T3";

export interface V1Digest {
  readonly sha256: string;
  /** The first commit (8 characters) whose version of the seed file exported this text. */
  readonly commit: string;
}

const CRM_API = join(import.meta.dir, "..");
const SEEDS = join(CRM_API, "src", "offer-templates", "wizardSeeds");
export const DATA_FILE = join(SEEDS, "v1Digests.ts");

const FILES: Readonly<Record<SeedCode, string>> = {
  T1: "welldChIt.T1.ts",
  T2: "welldChIt.T2.ts",
  T3: "welldChIt.T3.ts",
  T4: "welldChIt.T4.ts",
  T5: "welldChIt.T5.ts",
  T6: "welldChIt.T6.ts",
  "T1+T3": "welldChIt.T1T3.ts",
};
const CODES = Object.keys(FILES) as SeedCode[];

export const sha256 = (text: string): string => createHash("sha256").update(text, "utf8").digest("hex");

const git = (args: string[]): string => execFileSync("git", args, { cwd: CRM_API, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

/** The value a seed file exports, evaluated (so `\\` and `\`` in the template literal come out as the row will hold them). */
function exportedText(source: string): string {
  const match = /^export const \w+ = (`[\s\S]*`);\s*$/m.exec(source);
  if (!match) throw new Error("the revision does not end in `export const NAME = `…`;`");
  // the value of the template literal, escapes included; an interpolation would run code, so a revision with one is refused
  if (match[1]!.includes("${")) throw new Error("the revision interpolates a value");
  return new Function(`"use strict"; return ${match[1]};`)() as string;
}

/** Per code, the distinct v1 texts of the seed's history, oldest first, each with the commit that first exported it. */
export function v1Revisions(): Record<SeedCode, V1Digest[]> {
  const out = {} as Record<SeedCode, V1Digest[]>;
  for (const code of CODES) {
    const path = relative(git(["rev-parse", "--show-toplevel"]).trim(), join(SEEDS, FILES[code]));
    const commits = git(["log", "--format=%H", "--reverse", "--", join(SEEDS, FILES[code])]).split("\n").filter((line) => line !== "");
    const seen = new Set<string>();
    out[code] = [];
    for (const commit of commits) {
      let blob: string;
      try {
        blob = git(["show", `${commit}:${path}`]);
      } catch {
        continue; // a commit that deleted the file
      }
      const text = exportedText(blob);
      if (text.includes("@@field EMITTENTE")) continue; // a v2 text
      const digest = sha256(text);
      if (seen.has(digest)) continue;
      seen.add(digest);
      out[code].push({ sha256: digest, commit: commit.slice(0, 8) });
    }
  }
  return out;
}

/** The codes whose seed file has at least one v1 revision in the reachable history (none at all after the squash of 33ebd929). */
export const codesWithHistory = (found: Record<SeedCode, readonly V1Digest[]>): SeedCode[] => CODES.filter((code) => found[code].length > 0);

export const NO_HISTORY_NOTE = "no v1 revision in reachable history; v1Digests.ts is authoritative";

/** The data file as `--write` writes it. */
export function dataFile(found: Record<SeedCode, readonly V1Digest[]>): string {
  const lines = [
    "/**",
    " * The SHA-256 of every first-set (v1) revision of each wizard seed text, oldest first, with the commit that first exported it",
    " * (specs/20261115-crm-offer-wizard T61; DD-59, DD-60, AC-12.5). GENERATED by `bun scripts/seed-digests.ts --write` from the git",
    " * history of the seed files; never edited by hand (`--check` fails when it differs). T63's one-time upgrade replaces a stored",
    " * row only when its text hashes to one of these.",
    " */",
    "",
    'import type { WizardSeedCode } from "./welldChIt";',
    "",
    "export interface V1Digest {",
    "  readonly sha256: string;",
    "  /** The first commit (8 characters) whose version of the seed file exported this text. */",
    "  readonly commit: string;",
    "}",
    "",
    "export const V1_DIGESTS: Readonly<Record<WizardSeedCode, readonly V1Digest[]>> = {",
  ];
  for (const code of CODES) {
    lines.push(`  ${JSON.stringify(code)}: [`);
    for (const entry of found[code]) lines.push(`    { sha256: "${entry.sha256}", commit: "${entry.commit}" },`);
    lines.push("  ],");
  }
  lines.push("};", "");
  return lines.join("\n");
}

export interface Io {
  log(line: string): void;
  error(line: string): void;
}

/** Returns the process exit code. */
export async function runSeedDigests(argv: readonly string[], io: Io): Promise<number> {
  let values: { write?: boolean; check?: boolean };
  try {
    values = parseArgs({ args: [...argv], options: { write: { type: "boolean" }, check: { type: "boolean" } }, allowPositionals: false }).values;
  } catch (error) {
    io.error(`seed-digests: ${(error as Error).message}`);
    return 1;
  }
  const found = v1Revisions();
  if (values.write) {
    const missing = CODES.filter((code) => found[code].length === 0);
    if (missing.length > 0) {
      io.error(`seed-digests: refusing to write: no v1 revision in the history of ${missing.join(", ")}; it would wipe the recorded digests (v1Digests.ts is authoritative)`);
      return 1;
    }
    writeFileSync(DATA_FILE, dataFile(found));
    io.log(`wrote ${DATA_FILE}`);
  } else if (values.check) {
    const present = codesWithHistory(found);
    if (present.length === 0) {
      io.log(`seed-digests: ${NO_HISTORY_NOTE}`);
      return 0;
    }
    const recorded = (await import("../src/offer-templates/wizardSeeds/v1Digests")).V1_DIGESTS as Record<SeedCode, readonly V1Digest[]>;
    const differing = present.filter((code) => JSON.stringify(found[code]) !== JSON.stringify(recorded[code]));
    if (differing.length > 0) {
      io.error(`seed-digests: v1Digests.ts disagrees with the git history for ${differing.join(", ")}`);
      return 1;
    }
    io.log(`v1Digests.ts matches the git history (${present.join(", ")})`);
  }
  for (const code of CODES) io.log(`${code}: ${found[code].map((entry) => `${entry.sha256.slice(0, 12)} (${entry.commit})`).join(", ")}`);
  return 0;
}

if (import.meta.main) {
  process.exit(await runSeedDigests(process.argv.slice(2), { log: (line) => console.log(line), error: (line) => console.error(line) }));
}

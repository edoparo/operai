const harness = setupTestAuth();
await harness.init();

// @ts-expect-error -- the query suffix is a runtime-only cache-buster (testAuth.ts: no shared router specifier)
const { receiptCodeRouter } = (await import("./receiptCode.routes?receipt-code-qe-race")) as typeof import("./receiptCode.routes");
const { db } = await import("../lib/db");
const { __resetAuthzCacheForTests } = await import("../auth/authz.middleware");

const MANAGER: ResolveResponse = {
  sub: "",
  epoch: 1,
  permissions: [
    { resource: "refund", action: "access", conditions: null },
    { resource: "receipt-code", action: "manage", conditions: null },
  ],
  entity: null,
  jobTitle: null,
};
const OWNER = { userId: "u-luca", name: "Luca Conti", email: "luca.conti@welld.ch" };

beforeEach(async () => {
  await truncateRefundTables();
  __resetAuthzCacheForTests();
  harness.setResolve(async () => MANAGER);
});
afterAll(async () => {
  await truncateRefundTables();
});

async function putCode(code: string | null): Promise<number> {
  __resetAuthzCacheForTests();
  harness.setResolve(async () => MANAGER);
  const token = await harness.signToken({ sub: "acct-1", email: "acct-1@welld.ch" });
  const res = await receiptCodeRouter.request(`/accounting/receipt-codes/${OWNER.userId}`, {
    method: "PUT",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ code }),
  });
  await res.text();
  return res.status;
}

describe("two PUTs of different codes for one employee at once (AC-4.7, AC-4.10)", () => {
  it("20 repetitions behind a barrier: the history stays a chain and the last row's value is the one held", async () => {
    await db.refundRequest.create({ data: { ownerUserId: OWNER.userId, ownerEmail: OWNER.email, ownerName: OWNER.name, status: "submitted" } });
    const REPS = 20;
    for (let rep = 0; rep < REPS; rep++) {
      let release!: () => void;
      const gate = new Promise<void>((resolve) => (release = resolve));
      const a = gate.then(() => putCode("LCX"));
      const b = gate.then(() => putCode("LCY"));
      release();
      const statuses = await Promise.all([a, b]);
      expect(statuses).toEqual([200, 200]);
      // Reset to a known state outside the race (a clear is a change, so it extends the chain).
      expect(await putCode(null)).toBe(200);
    }
    const history = await db.receiptCodeChange.findMany({ where: { ownerUserId: OWNER.userId }, orderBy: { id: "asc" } }); // cuid: generated by the client after the lock, so id order is the serial order
    let held: string | null = null;
    for (const [i, change] of history.entries()) {
      expect({ i, before: change.codeBefore }).toEqual({ i, before: held });
      held = change.codeAfter;
    }
    expect(held).toBeNull();
    expect(await db.receiptCode.count({ where: { ownerUserId: OWNER.userId } })).toBe(0);
  });
});

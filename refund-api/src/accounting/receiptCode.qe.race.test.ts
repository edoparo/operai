/**
 * QE gap test (T27, specs/20261124-receipt-numbers-from-the-register; AC-4.7, AC-4.10): two PUTs of DIFFERENT codes for the SAME
 * employee at the same moment. The per-employee advisory lock of the PUT serialises them, so the change history is a chain: each row's
 * `codeBefore` is the previous row's `codeAfter` and the last `codeAfter` is what the employee holds. Found by a mutation check:
 * removing the lock left every existing test green. Real Postgres, jwt/authz mocked.
 */


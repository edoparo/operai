/**
 * Localized display name for an ISO 3166-1 alpha-2 code, via
 * `Intl.DisplayNames` — the SAME standard Web API
 * `auth/src/profile/address.format.ts` already uses server-side (plan.md R8).
 * Falls back to the raw code if `Intl.DisplayNames` is unavailable or returns
 * nothing — degraded, never broken. Never throws.
 */
export const countryDisplayName = (code: string, locale: Locale = resolveLocale()): string => {
  try {
    if (typeof Intl === 'undefined' || typeof Intl.DisplayNames === 'undefined') return code
    const displayNames = new Intl.DisplayNames([locale], { type: 'region' })
    return displayNames.of(code) ?? code
  } catch {
    return code
  }
}

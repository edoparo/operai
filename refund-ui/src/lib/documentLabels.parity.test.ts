/**
 * refund-ui's half of the label contract.
 *
 * The canonical table is `refund-api/src/requests/document-labels.json`, and
 * refund-api asserts against it in `labels.test.ts`. This file transcribes the
 * SAME values and asserts this package's own sources match them, so a label
 * changed on one side of the boundary fails the other side's suite.
 *
 * Transcribed rather than imported on purpose: refund-api (Bun) and refund-ui
 * (pnpm) are deliberately not npm-linked — CLAUDE.md's ### Git explains that a
 * workspace would break the per-app installs and the Vercel/Railway deploys —
 * and reaching across with a relative import would break this package's build
 * root. Same mechanism `computeMileageAmountCents` already uses for ADR 20260720-mileage-rate-money-precision-integer-micros's
 * money vectors.
 *
 * WHY IT MATTERS: the exported PDF is generated by refund-api and read next to
 * this UI. When they disagree, an accountant sees "travel_km" on paper and
 * "Travel — mileage (km)" on screen and cannot tell whether they are looking
 * at the same record.
 */

import { describe, expect, it } from 'vitest'
import { EXPENSE_TYPES } from './expenseTypes'
import { catalogs } from '../strings'

/** Verbatim from refund-api/src/requests/document-labels.json. */
const CANONICAL = {
  expenseType: {
    travel_highway: 'Travel — highway',
    travel_km: 'Travel — mileage (km)',
    travel_parking: 'Travel — parking',
    travel_train: 'Travel — train',
    travel_other_public_transport: 'Travel — other public transport',
    travel_flight: 'Travel — flight',
    travel_taxi: 'Travel — taxi',
    company_manuals: 'Company manuals',
    stationery: 'Stationery',
    representation_meals: 'Meals with clients',
    representation_gifts: 'Representation — gifts',
    office_material: 'Office material',
    postal: 'Postal',
    telephone: 'Telephone',
  },
  expenseTypeIt: {
    travel_highway: 'Spese di viaggio (autostrada)',
    travel_km: 'Spese di viaggio (km)',
    travel_parking: 'Spese di viaggio (parcheggio)',
    travel_train: 'Spese di viaggio (treno)',
    travel_other_public_transport: 'Spese di viaggio (altri mezzi pubblici)',
    travel_flight: 'Spese di viaggio (aereo)',
    travel_taxi: 'Spese di viaggio (taxi)',
    company_manuals: 'Spese manualistica societaria',
    stationery: 'Spese di cancelleria',
    representation_meals: 'Pranzi/cene con clienti',
    representation_gifts: 'Spese di rappresentanza (regali)',
    office_material: 'Spese materiale ufficio',
    postal: 'Spese postali',
    telephone: 'Spese telefoniche',
  },
  entity: {
    welld_it: 'WellD Italia',
    welld_ch: 'WellD CH',
  },
  requestStatus: {
    draft: 'Draft',
    submitted: 'Awaiting decision',
    approved: 'Approved',
    rejected: 'Rejected',
    paid: 'Paid',
  },
} as const

// The PDFs are English, so the ENGLISH catalog is the one that must match —
// whatever language the test run (or the person) resolves to (INC-25).
describe('document label parity with refund-api', () => {
  it('every expense type label matches the canonical table', () => {
    for (const option of EXPENSE_TYPES) {
      expect(option.labelEn).toBe(CANONICAL.expenseType[option.id as keyof typeof CANONICAL.expenseType])
    }
  })

  it('every Italian label matches the canonical table (the register extract is Italian)', () => {
    for (const option of EXPENSE_TYPES) {
      expect(option.labelIt).toBe(CANONICAL.expenseTypeIt[option.id as keyof typeof CANONICAL.expenseTypeIt])
    }
  })

  it('the catalogue has exactly the canonical set of types — none added or dropped', () => {
    expect(EXPENSE_TYPES.map((o) => o.id).sort()).toEqual(Object.keys(CANONICAL.expenseType).sort())
  })

  it('entity labels match', () => {
    expect(catalogs.en.badges.entity).toMatchObject(CANONICAL.entity)
  })

  it('request status labels match', () => {
    expect(catalogs.en.badges.requestStatus).toMatchObject(CANONICAL.requestStatus)
  })
})
